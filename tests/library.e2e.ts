test('meets Chromium installability requirements and supports portrait touch navigation and pinch zoom', async ({}, testInfo) => {
  const context = await chromium.launchPersistentContext(testInfo.outputPath('browser-profile'), {
    executablePath: process.env.FOLIO_CHROMIUM || undefined,
    viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2,
  })
  try {
    const page = await context.newPage()
    await page.goto('http://localhost:4173/')
    await expect(page.getByRole('heading', { name: 'My Library' })).toBeVisible()
    await expect.poll(() => page.evaluate(() => navigator.serviceWorker.controller?.state), { timeout: 15000 }).toBe('activated')
    const cdp = await context.newCDPSession(page)
    const installability = await cdp.send('Page.getInstallabilityErrors')
    expect(installability.installabilityErrors).toEqual([])
    await page.getByRole('button', { name: 'Resume reading' }).click()
    await expect(paper(page, 12)).toBeVisible()
    await expect(page.locator('.flipbook.single')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
    const box = (await paper(page, 12).boundingBox())!
    const y = Math.round(box.y + box.height * .78)
    const x = Math.round(box.x + box.width * .82)
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x - 138, y }] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await expect(pageControl(page)).toHaveValue('13')
    await expect(paper(page, 13)).toBeVisible()
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 150, y, id: 1 }, { x: 238, y, id: 2 }] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 122, y, id: 1 }, { x: 267, y, id: 2 }] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await expect(page.getByRole('button', { name: /16[0-9]%/ })).toBeVisible()
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 265, y }] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 140, y }] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await expect.poll(() => page.locator('.reader-viewport').evaluate(element => element.scrollLeft)).toBeGreaterThan(20)
    await expect(pageControl(page)).toHaveValue('13')
  } finally {
    await context.close()
  }
})

