async function createPdf(count: number) {
  const pdf = await PDFDocument.create()
  const font = await pdf.embedFont(StandardFonts.Helvetica)
  pdf.setTitle('Research notebook')
  for (let index = 0; index < count; index++) {
    const page = pdf.addPage(index % 2 === 0 ? [380, 540] : [540, 380])
    page.drawText(index + 1 === count ? 'End of research notebook' : 'Proof and diagram: E = mc^2', { x: 35, y: 330, font, size: 16 })
    page.drawRectangle({ x: 35, y: 203, width: 130, height: 60, borderColor: rgb(.1, .2, .3), borderWidth: 2 })
    page.drawLine({ start: { x: 35, y: 233 }, end: { x: 165, y: 233 }, thickness: 1 })
  }
  return Buffer.from(await pdf.save())
}

