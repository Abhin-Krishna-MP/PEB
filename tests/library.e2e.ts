test('keeps the book and scroll area fixed throughout a page turn', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.goto('/')
  await sampleOpen(page).click()
  await expect(paper(page, 12)).toBeVisible()
  const next = page.getByRole('button', { name: 'Next page' })
  const frames = await next.evaluate(async (button: HTMLButtonElement) => {
    const viewport = document.querySelector('.reader-viewport')!
    const book = document.querySelector('.spread-pages')!
    function snapshot() {
      const { x, y, width, height } = book.getBoundingClientRect()
      return [x, y, width, height, viewport.scrollWidth, viewport.scrollHeight, viewport.scrollLeft, viewport.scrollTop]
    }
    const initial = snapshot()
    const during: number[][] = []
    button.click()
    const deadline = performance.now() + 2000
    do {
      await new Promise(requestAnimationFrame)
      if (document.querySelector('.turn-leaf')) during.push(snapshot())
    } while (performance.now() < deadline && (!during.length || document.querySelector('.turn-leaf')))
    return { initial, during, final: snapshot() }
  })
  expect(frames.during.length).toBeGreaterThan(1)
  expect([...frames.during, frames.final].every(frame => frame.every((value, index) => value === frames.initial[index]))).toBe(true)
  await expect(pageControl(page)).toHaveValue('13')
})

test('exports a portable flipbook that opens and turns pages offline', async ({ page, context }, testInfo) => {
  await page.goto('/')
  await expect(sampleOpen(page)).toBeVisible()
  await filePicker(page).setInputFiles({ name: 'research.pdf', mimeType: 'application/pdf', buffer: await createPdf(2) })
  await expect(paper(page, 2)).toBeVisible()
  await expect.poll(() => page.evaluate(() => navigator.serviceWorker.controller?.state), { timeout: 15000 }).toBe('activated')
  await context.setOffline(true)
  await page.getByRole('button', { name: 'Reader options' }).click()
  await page.getByRole('button', { name: 'Export HTML flipbook' }).click()
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download HTML' }).click()
  const path = testInfo.outputPath('book.html')
  await (await downloaded).saveAs(path)
  const exported = await context.newPage()
  const networkRequests: string[] = []
  exported.on('request', request => {
    if (/^https?:/.test(request.url())) networkRequests.push(request.url())
  })
  // Managed Chromium may restrict file:// navigation. Run the saved file's
  // bytes on an independent blank page with networking still disabled.
  await exported.setContent(await readFile(path, 'utf8'))
  await expect(exported.getByRole('heading', { name: 'Research notebook' })).toBeVisible()
  await expect(exported.getByText('1 / 2')).toBeVisible()
  await expect.poll(() => exported.getByRole('img').evaluate(image => (image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  await exported.getByRole('button', { name: 'Next' }).click()
  await expect(exported.getByText('2 / 2')).toBeVisible()
  expect(networkRequests).toEqual([])
})
