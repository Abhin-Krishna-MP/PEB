test('renders and resumes a 205-page mixed-orientation PDF after an offline restart', async ({ page, context }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Upload PDF', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Choose PDF files' })).toBeVisible()
  await filePicker(page).setInputFiles({ name: 'research.pdf', mimeType: 'application/pdf', buffer: await createPdf(205) })
  await expect(paper(page, 1)).toBeVisible()
  const layout = await page.locator('.spread-pages .pdf-paper').evaluateAll(elements => elements.map(element => element.clientWidth / element.clientHeight))
  expect(layout[0]).toBeLessThan(1)
  expect(layout[1]).toBeGreaterThan(1)
  await pageControl(page).fill('205')
  await pageControl(page).press('Enter')
  await expect(paper(page, 205)).toBeVisible()
  await expect(page.locator('.reader-viewport canvas')).toHaveCount(1)
  await page.getByRole('button', { name: 'Bookmark this page' }).click()
  await expect(page.getByRole('button', { name: 'Remove page bookmark' })).toBeVisible()
  await expect.poll(() => page.evaluate(() => navigator.serviceWorker.controller?.state), { timeout: 15000 }).toBe('activated')
  const readingUrl = page.url()
  await page.close()
  await context.setOffline(true)
  const reopened = await context.newPage()
  await reopened.goto(readingUrl)
  await expect(paper(reopened, 205)).toBeVisible()
  await expect(pageControl(reopened)).toHaveValue('205')
  await expect(reopened.getByRole('button', { name: 'Remove page bookmark' })).toBeVisible()
  await reopened.getByRole('button', { name: 'Library', exact: true }).click()
  await expect(reopened.getByText('Offline', { exact: true })).toBeVisible()
  await expect(reopened.getByRole('button', { name: 'Open Research notebook' })).toBeVisible()
})

